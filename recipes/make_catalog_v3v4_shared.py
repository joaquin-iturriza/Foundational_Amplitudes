#!/usr/bin/env python
"""The probes held out in both catalogs, for the catalog_v4 short pretrainings' like-for-like read (catalog_coverage):
a process held out in catalog_v3 (any of its main arm's axes H1, H2, H2p5, H3, H5, H6, H7c) and in catalog_v4 (the same
axes), matched by name without the v3_/v4_ prefix. H7E is left out (catalog_v3's energy probes span 1 to 10 TeV,
catalog_v4's 6 to 20 TeV: different pools under different names), and so are H3p and H4, which only the removal twin
holds out. Each catalog's model then reads the other catalog's pools of these probes, besides its own axes, so both are
scored on the same events. Two recipes, each with its catalog's top-level keys (its sampling block, which names the pools):
    recipes/catalog_v3_shared_heldout.yaml   catalog_v3's pools of the shared probes (v3_<name>)
    recipes/catalog_v4_shared_heldout.yaml   catalog_v4's pools of the same probes (v4_<name>)
The entries are the axis files' own (the axis is read back from them). Prints the count per axis pair.
    python recipes/make_catalog_v3v4_shared.py
"""
import collections, os

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AXES = ("H1", "H2", "H2p5", "H3", "H5", "H6", "H7c")


def held_out(cat):
    """name without prefix -> (axis, recipe entry); and the axis files' shared top-level keys"""
    out, top = {}, None
    for a in AXES:
        r = yaml.safe_load(open(os.path.join(ROOT, f"recipes/catalog_{cat}_heldout_{a}.yaml")))
        t = {k: v for k, v in r.items() if k != "processes"}
        assert top is None or t == top, f"{cat} {a}: top-level keys differ from the other axes"
        top = t
        for p in r["processes"]:
            out[p["name"][len(cat) + 1:]] = (a, p)
    return out, top


def main():
    (h3, t3), (h4, t4) = held_out("v3"), held_out("v4")
    common = sorted(set(h3) & set(h4))
    for cat, h, top in (("v3", h3, t3), ("v4", h4, t4)):
        ps = [h[n][1] for n in common]
        with open(os.path.join(ROOT, f"recipes/catalog_{cat}_shared_heldout.yaml"), "w") as f:
            f.write("# generated by recipes/make_catalog_v3v4_shared.py; do not edit\n")
            yaml.safe_dump({**top, "processes": ps}, f, sort_keys=False)
    pairs = collections.Counter((h3[n][0], h4[n][0]) for n in common)
    print(f"held out in both: {len(common)} (catalog_v3 {len(h3)}, catalog_v4 {len(h4)});",
          ", ".join(f"{a}/{b} {c}" for (a, b), c in sorted(pairs.items())))


if __name__ == "__main__":
    main()
