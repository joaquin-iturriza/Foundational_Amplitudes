#!/usr/bin/env python
"""The training recipe of catalog_v4's arm with more sign-changing one-loop pools (v4_dimensionless_muon_more_signed;
plan v3_prep_explore, the design of 2026-10-29): recipes/catalog_v4_train.yaml unchanged plus, from the extension
recipes/catalog_v4_gen_signext.yaml (123 one-loop pools of the coloured 2->3 training tree classes outside the one-loop
layer), only the pools whose train role holds events of both signs and no audit flag, read from the extension's audit
(analysis/catalog_v3/pool_audit.py --stages v4_signext). As recipes/make_catalog_v3_train_signext.py.
Before writing, the certification failures (prebuild_recipes.py --skip-cert-failed's list) are counted: more than a fifth
of the extension refuses (exit 3), the design then comes back before training. Runs on the site after the generation
(scripts/job_catalog_v4_signext.sh), writing outside the checkout:
    python recipes/make_catalog_v4_train_signext.py --audit A.json --cert-failed F.txt --out R.yaml
"""
import argparse, json, os, sys

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAX_FAIL_FRAC = 0.2      # the design: "if more than a fifth of the 123 fail the design comes back before training"


def build(base, ext, audit, failed):
    """(recipe dict, summary): base's processes, then the extension's entries whose train split is mixed-sign"""
    have = {p["name"] for p in base["processes"]}
    assert not have & {e["name"] for e in ext}, sorted(have & {e["name"] for e in ext})
    keep = [e for e in ext if e["name"] not in failed and e["name"] in audit and not audit[e["name"]]["flags"]
            and 0 < audit[e["name"]]["train"]["negative"] < 1]
    out = {**{k: v for k, v in base.items() if k != "processes"}, "processes": base["processes"] + keep}
    summ = {"base": len(base["processes"]), "extension": len(ext), "cert_failed": sorted(failed),
            "flagged": sorted(e["name"] for e in ext if e["name"] not in failed and audit.get(e["name"], {}).get("flags")),
            "one_sign": sorted(e["name"] for e in ext if e["name"] not in failed and e["name"] in audit
                               and not audit[e["name"]]["flags"] and not 0 < audit[e["name"]]["train"]["negative"] < 1),
            "kept": [e["name"] for e in keep], "total": len(out["processes"])}
    return out, summ


def read_failed(path):
    """prebuild_recipes.py's LIST_FILE: `name<TAB>reason` lines, `#quarantined` lines after them"""
    if not path or not os.path.exists(path):
        return {}
    return dict(l.rstrip("\n").split("\t", 1) for l in open(path) if l.strip() and not l.startswith("#"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--audit", required=True, help="pool_audit.py --stages v4_signext's json")
    ap.add_argument("--cert-failed", default=None, help="prebuild_recipes.py --skip-cert-failed's list")
    ap.add_argument("--out", required=True)
    ap.add_argument("--summary", default=None, help="where to write the kept / dropped lists (json)")
    a = ap.parse_args()
    base = yaml.safe_load(open(os.path.join(ROOT, "recipes/catalog_v4_train.yaml")))
    ext = yaml.safe_load(open(os.path.join(ROOT, "recipes/catalog_v4_gen_signext.yaml")))["processes"]
    failed = read_failed(a.cert_failed)
    out, summ = build(base, ext, json.load(open(a.audit))["pools"], failed)
    if a.summary:
        json.dump({**summ, "cert_failed_reasons": failed}, open(a.summary, "w"), indent=1)
    print(f"V4_SIGNEXT cert_failed {len(failed)}/{len(ext)}: {sorted(failed)}")
    print(f"V4_SIGNEXT flagged {len(summ['flagged'])}: {summ['flagged']}")
    print(f"V4_SIGNEXT one_sign {len(summ['one_sign'])}; kept {len(summ['kept'])}")
    if len(failed) > MAX_FAIL_FRAC * len(ext):
        print(f"V4_SIGNEXT_REFUSED {len(failed)} of {len(ext)} failed certification (> {MAX_FAIL_FRAC:.0%}): "
              "the design comes back before training")
        sys.exit(3)
    with open(a.out, "w") as f:
        f.write("# generated by recipes/make_catalog_v4_train_signext.py; do not edit\n")
        yaml.safe_dump(out, f, sort_keys=False)
    print(f"V4_SIGNEXT catalog_v4_train {summ['base']} + {len(summ['kept'])} sign-changing one-loop pools of "
          f"{len(ext)} = {summ['total']} -> {a.out}")


if __name__ == "__main__":
    main()
