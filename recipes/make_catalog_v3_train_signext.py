#!/usr/bin/env python
"""The training recipe of the one-loop sign transfer's arm with more sign-changing pools (baseline_more_signed):
recipes/catalog_v3_train.yaml plus, from the extension recipes/catalog_v3_gen_signext.yaml (153 one-loop pools of the
coloured 2->3 training tree classes), only the pools whose train role holds events of both signs, read from the
extension's audit (analysis/catalog_v3/pool_audit.py --stages signext -> analysis/catalog_v3/pool_audit_signext.json).
    python recipes/make_catalog_v3_train_signext.py
"""
import json, os

import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    base = yaml.safe_load(open(os.path.join(ROOT, "recipes/catalog_v3_train.yaml")))
    ext = yaml.safe_load(open(os.path.join(ROOT, "recipes/catalog_v3_gen_signext.yaml")))["processes"]
    au = json.load(open(os.path.join(ROOT, "analysis/catalog_v3/pool_audit_signext.json")))["pools"]
    have = {p["name"] for p in base["processes"]}
    keep = [e for e in ext if not au[e["name"]]["flags"] and 0 < au[e["name"]]["train"]["negative"] < 1
            and e["name"] not in have]
    out = {**{k: v for k, v in base.items() if k != "processes"}, "processes": base["processes"] + keep}
    with open(os.path.join(ROOT, "recipes/catalog_v3_train_signext.yaml"), "w") as f:
        f.write("# generated by recipes/make_catalog_v3_train_signext.py; do not edit\n")
        yaml.safe_dump(out, f, sort_keys=False)
    print(f"catalog_v3_train {len(base['processes'])} + {len(keep)} sign-changing one-loop pools of {len(ext)} "
          f"= {len(out['processes'])}")


if __name__ == "__main__":
    main()
