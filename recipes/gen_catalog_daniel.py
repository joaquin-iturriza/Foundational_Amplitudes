#!/usr/bin/env python
"""catalog_daniel: the process catalog of arXiv:2606.23791 (LLM4LHC; Bahl, Plehn, Schiller,
Sivagnanalingam), regenerated by us with THEIR event generation and labelled with our |M|^2.

Source (MIT, recipes/catalog_daniel/src/LICENSE), copied verbatim from their repository
(github LLM4LHC, data/parton/, commit 3e19bc3):
  process_catalog_sm.json  1501 partonic processes (10 2->1, 254 2->2, 1237 2->3)
  test_split.json          their hold-out: 149 folders in 14 groups (6 interpolation, 8 extrapolation)
  run_card.dat             MadEvent run card (pp at 2 x 6500 GeV, nn23lo1, dynamical scale -1,
                           bwcutoff 15, nhel 0, sde_strategy 1, pT >= 10 / |eta| <= 5 on j b a l nu,
                           maxjetflavor 5); used VERBATIM except nevents and iseed
  param_card_sm.dat        MG default sm (restrict_default) with alpha_s 0.13 (unused: the PDF sets it)
  sm_processes.txt, diagram_counts_sm.json   reference only

What this script writes (the pipeline reads recipes/catalog_daniel_processes.yaml at import):
  recipes/catalog_daniel_processes.yaml   one PROCESSES entry per kept process, kind lhe_pp
  recipes/catalog_daniel_train.yaml       their training processes (1352)
  recipes/catalog_daniel_heldout.yaml     their held-out processes (139: the published 149 minus
                                          the ten 2->1, a whole group of their split)
  recipes/catalog_daniel_heldout_norelabel.yaml   the held-out processes that are NOT an exact
                                          relabelling of a training process (side list)
  recipes/catalog_daniel_heldout_relabels.json    held-out folder -> the training folders it relabels
  recipes/catalog_daniel_all.yaml         all 1491

Decisions: D51 ("just generate the data": the catalog, momenta and |M|^2, made by us) and D54
("For now let's do only 100k."). Two choices below are the main session's reading, NOT user words,
and await the user's call (repo-reviewer 2026-10-15): the hold-out as published although 96 of its 139
processes are exact relabellings of a training process (CLAUDE.md: a held-out process is held out
with its whole class; only _heldout_norelabel carries a clean held-out claim until then), and the top
mass 173.0 (their card) against our table's 172.5. The relabel classes come from the symbolic
analysis/catalog_daniel/classify2.py, not from the numeric tools/equal_processes.py check.
  - the ten 2->1 processes are dropped everywhere, as they drop them;
  - the hold-out is their split as published, no class-based removal on top (pending, above); the relabel side
    list uses analysis/catalog_daniel/classes_default.json (exact_key, default coupling orders);
  - 100k train events per process (they used 1M), 10k val, 10k test, all from ONE MadEvent run per
    process (datagen.ensure_lhe_pp), so the three roles are disjoint unweighted events;
  - the coupling-order vector is [0, 0, max QCD, max QED] over the amplitude orders MadGraph picks
    by default (classes_default.json "orders"), which is what their events carry;
  - the top mass is THEIR 173.0 GeV in generation and labelling (their param card); our particle
    table and the e+e-/qq catalogs use 172.5 (mg.LOCKED_MT). The table's log-mass feature is
    therefore 0.3% off for the top in this catalog; the momenta carry 173.0.

Names: dc_<their folder> (e.g. dc_gb_bbbx), so no entry can collide with a hand-written or a
catalog_v2 process.

Usage:
  python recipes/gen_catalog_daniel.py [--copy-from <LLM4LHC>/data/parton]   # write everything
  python recipes/gen_catalog_daniel.py --check                              # unit checks only
"""
import argparse, json, os, shutil, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REC = os.path.join(ROOT, "recipes")
SRC = os.path.join(REC, "catalog_daniel", "src")
CLASSES = os.path.join(ROOT, "analysis", "catalog_daniel", "classes_default.json")
SRC_FILES = ("process_catalog_sm.json", "test_split.json", "run_card.dat", "param_card_sm.dat",
             "sm_processes.txt", "diagram_counts_sm.json")
PREFIX = "dc_"
SQRTS = [13000, 13000]          # pp at 2 x 6500 GeV; partonic sqrt(s) varies per event (PDFs)
N_TRAIN, N_VAL, N_TEST = 100000, 10000, 10000

# MadGraph particle name -> PDG (sm), the names their catalog uses
MG5_PDG = {"e-": 11, "e+": -11, "mu-": 13, "mu+": -13, "ta-": 15, "ta+": -15,
           "ve": 12, "ve~": -12, "vm": 14, "vm~": -14, "vt": 16, "vt~": -16,
           "u": 2, "u~": -2, "d": 1, "d~": -1, "s": 3, "s~": -3, "c": 4, "c~": -4,
           "b": 5, "b~": -5, "t": 6, "t~": -6, "g": 21, "a": 22, "z": 23,
           "w+": 24, "w-": -24, "h": 25}


def card_masses(param_card):
    """|PDG| -> mass from the SLHA Block MASS of `param_card` (their card; W from its comment line)."""
    m, blk = {}, None
    for line in open(param_card):
        s = line.split("#")[0].strip()
        if not s:
            continue
        t = s.split()
        if t[0].lower() == "block":
            blk = t[1].lower()
            continue
        if t[0].lower() == "decay":
            blk = None
            continue
        if blk == "mass" and len(t) >= 2:
            m[abs(int(t[0]))] = float(t[1])
    return m


def load(src=SRC):
    cat = json.load(open(os.path.join(src, "process_catalog_sm.json")))
    split = json.load(open(os.path.join(src, "test_split.json")))
    classes = json.load(open(CLASSES))
    return cat, split, classes


def build(src=SRC):
    """Returns (entries {name: PROCESSES entry}, stats dict, relabels {held folder: [train folders]})."""
    cat, split, classes = load(src)
    masses = card_masses(os.path.join(src, "param_card_sm.dat"))
    held = {f: (kind, g["group"]) for kind, gs in split.items() for g in gs for f in g["folders"]}
    by_folder = {r["folder"]: r for r in classes["processes"]}
    entries = {}
    for x in cat:
        fin, ini = x["outgoing"], x["incoming"]
        if len(fin) < 2:
            continue                                    # 2->1: dropped, as they drop them
        rec = by_folder[x["folder"]]
        assert rec["process"] == x["madgraph_process"], x["folder"]
        pdg = [MG5_PDG[p] for p in ini] + [MG5_PDG[p] for p in fin]
        assert pdg[2:] == list(x["pdg_ids_outgoing"]), x["folder"]
        qcd = max(int(o.get("QCD", 0)) for o in rec["orders"])
        qed = max(int(o.get("QED", 0)) for o in rec["orders"])
        assert qcd + qed == len(fin), (x["folder"], rec["orders"])   # tree level: total degree nfinal
        h = held.get(x["folder"])
        entries[PREFIX + x["folder"]] = {
            "kind": "lhe_pp",
            "folder": x["folder"],
            "mg5_generate": [f"generate {x['madgraph_process']}"],
            "proc_str": x["proc_str"],
            "nfinal": len(fin),
            "pdg_ids": pdg,
            "m_finals": [float(masses.get(abs(p), 0.0)) for p in pdg[2:]],
            "order": [0, 0, qcd, qed],
            "alphas_power": qcd,
            "n_diagrams": int(rec["n_diagrams"]),
            "split": "heldout" if h else "train",
            "test_group": f"{h[0]}: {h[1]}" if h else None,
        }
    # side list: held-out processes that are an exact relabelling of a TRAINING process
    train_keys = {}
    for r in classes["processes"]:
        n = PREFIX + r["folder"]
        if n in entries and entries[n]["split"] == "train":
            train_keys.setdefault(r["exact_key"], []).append(r["folder"])
    relabels = {}
    for r in classes["processes"]:
        n = PREFIX + r["folder"]
        if n in entries and entries[n]["split"] == "heldout" and r["exact_key"] in train_keys:
            relabels[r["folder"]] = sorted(train_keys[r["exact_key"]])
    stats = {
        "read": len(cat),
        "kept": len(entries),
        "dropped_2to1": len(cat) - len(entries),
        "heldout_published": len(held),
        "heldout_published_2to1": sum(1 for x in cat if x["folder"] in held and len(x["outgoing"]) < 2),
        "heldout": sum(1 for e in entries.values() if e["split"] == "heldout"),
        "train": sum(1 for e in entries.values() if e["split"] == "train"),
        "initial_b_all": sum(1 for x in cat if set(x["incoming"]) & {"b", "b~"}),
        "initial_b_kept": sum(1 for e in entries.values() if {5, -5} & set(e["pdg_ids"][:2])),
        "by_nfinal": {n: sum(1 for e in entries.values() if e["nfinal"] == n) for n in (2, 3)},
        "heldout_relabel_of_train": len(relabels),
    }
    return entries, stats, relabels


def check(entries, stats, relabels):
    """The counts the catalog must have (their paper/repo: 1501 = 10 + 254 + 1237; 149 held out,
    10 of them the 2->1 group; 347 processes with an initial b, 2 of them 2->1)."""
    assert stats["read"] == 1501, stats
    assert stats["kept"] == 1491, stats
    assert stats["by_nfinal"] == {2: 254, 3: 1237}, stats
    assert stats["heldout_published"] == 149, stats
    assert stats["heldout_published_2to1"] == 10, stats
    assert stats["heldout"] == 139 and stats["train"] == 1352, stats
    assert stats["initial_b_all"] == 347 and stats["initial_b_kept"] == 345, stats
    for n, e in entries.items():
        assert len(e["pdg_ids"]) == e["nfinal"] + 2 and len(e["m_finals"]) == e["nfinal"], n
        assert sum(e["order"][2:]) == e["nfinal"], n
    # the top carries THEIR mass (173.0), never our table's 172.5
    tops = [e for e in entries.values() if 6 in map(abs, e["pdg_ids"][2:])]
    assert tops and all(m == 173.0 for e in tops for p, m in zip(e["pdg_ids"][2:], e["m_finals"]) if abs(p) == 6)
    assert all(f"{PREFIX}{f}" in entries and entries[f"{PREFIX}{f}"]["split"] == "heldout" for f in relabels)
    print("checks ok:", json.dumps(stats))


def recipe_yaml(path, names, header):
    lines = [f"# {h}" if h else "#" for h in header]
    lines += ["processes:"]
    for n in names:
        lines.append(f"  - {{name: {n + ',':30s} sqrts: [{SQRTS[0]}, {SQRTS[1]}], "
                     f"n_train: {N_TRAIN}, n_val: {N_VAL}, n_test: {N_TEST}}}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def write(entries, stats, relabels):
    hdr = ["catalog_daniel: the 1491 2->2 / 2->3 processes of arXiv:2606.23791 (LLM4LHC), regenerated with",
           "their MadEvent setup (recipes/catalog_daniel/src, MIT) and labelled with our standalone_cpp |M|^2",
           "at each event's alpha_s. Written by recipes/gen_catalog_daniel.py; do not edit by hand.",
           "The pipeline loads these entries into mg5_pipeline_final.PROCESSES at import (kind lhe_pp).",
           "Top mass 173.0 GeV (their param card), not our table's 172.5."]
    doc = {
        "lhe": {
            "cards_dir": "recipes/catalog_daniel/src",
            "run_card": "run_card.dat",
            "param_card": "param_card_sm.dat",
            "model": "sm",
            # one MadEvent run per process: [val | test | train] blocks of the shuffled events
            "n_val": N_VAL, "n_test": N_TEST, "n_train": N_TRAIN,
            "source": "github LLM4LHC data/parton @ 3e19bc3 (MG5 3.5.12 there)",
        },
        "processes": entries,
    }
    with open(os.path.join(REC, "catalog_daniel_processes.yaml"), "w") as f:
        f.write("".join(f"# {h}\n" for h in hdr))
        yaml.safe_dump(doc, f, sort_keys=False, width=200, default_flow_style=None)
    names = list(entries)
    train = [n for n in names if entries[n]["split"] == "train"]
    held = [n for n in names if entries[n]["split"] == "heldout"]
    norel = [n for n in held if entries[n]["folder"] not in relabels]
    common = ["pp at 13 TeV through MadEvent (their run_card), one run per process: val 10k | test 10k | train",
              "100k (they used 1M). Built by prebuild_recipes.py (datagen.ensure_lhe_pp; scripts/job_gen_daniel_catalog.sh).",
              "sqrts is the hadronic 13 TeV (a label of the pool path), not a sampling window."]
    recipe_yaml(os.path.join(REC, "catalog_daniel_train.yaml"), train,
                [f"catalog_daniel train: their {len(train)} training processes (the 1491 minus their hold-out)."] + common)
    recipe_yaml(os.path.join(REC, "catalog_daniel_heldout.yaml"), held,
                [f"catalog_daniel held-out: their published test_split.json ({stats['heldout_published']} folders) minus the",
                 f"{stats['heldout_published_2to1']} 2->1 processes (their whole 'Single-particle production' group) = {len(held)}.",
                 "No class-based removal on top; catalog_daniel_heldout_norelabel.yaml is the relabel-free subset."] + common)
    recipe_yaml(os.path.join(REC, "catalog_daniel_heldout_norelabel.yaml"), norel,
                [f"catalog_daniel held-out without the {len(relabels)} processes that are an exact relabelling of a training",
                 "process (analysis/catalog_daniel/classes_default.json exact_key; list in catalog_daniel_heldout_relabels.json)."]
                + common)
    recipe_yaml(os.path.join(REC, "catalog_daniel_all.yaml"), names,
                [f"catalog_daniel all: the {len(names)} kept processes (train + held-out)."] + common)
    with open(os.path.join(REC, "catalog_daniel_heldout_relabels.json"), "w") as f:
        json.dump(relabels, f, indent=1, sort_keys=True)
    print(f"wrote catalog_daniel_processes.yaml ({len(names)}), _train ({len(train)}), _heldout ({len(held)}), "
          f"_heldout_norelabel ({len(norel)}), _all, _heldout_relabels.json ({len(relabels)})")


def copy_sources(parton_dir):
    os.makedirs(SRC, exist_ok=True)
    for f in SRC_FILES:
        shutil.copy2(os.path.join(parton_dir, f), os.path.join(SRC, f))
    lic = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(parton_dir))), "LICENSE")
    shutil.copy2(lic, os.path.join(SRC, "LICENSE"))
    print(f"copied {len(SRC_FILES)} files + LICENSE from {parton_dir}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--copy-from", help="their data/parton directory (refreshes recipes/catalog_daniel/src)")
    ap.add_argument("--check", action="store_true", help="unit checks only, write nothing")
    a = ap.parse_args()
    if a.copy_from:
        copy_sources(a.copy_from)
    entries, stats, relabels = build()
    check(entries, stats, relabels)
    if not a.check:
        write(entries, stats, relabels)


if __name__ == "__main__":
    main()
