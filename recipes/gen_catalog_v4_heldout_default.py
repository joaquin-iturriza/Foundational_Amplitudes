"""Default-sampled test pools of catalog_v4's held-out classes that have none (plan catalog_coverage step 18; Joaquin,
2026-10-31 [D227]: the held-out check is against data generated the default way). The classes of H1-H3 are read on
their PP4/EE4 pools (pp13v4_/pp13_/ee4_); the 142 others (analysis/catalog_v4/heldout_default_pools.py) get here a
MadEvent pool at their own axis's settings, named hd_<the held-out class's name without v4_>, so the readers'
class map (analysis/catalog_v4/mixture_ab.py class_of) gives each probe its held-out class:

  H2p5  the 5-body classes: pp at 13 TeV with catalog_v4_pp's cards (as pp13v4_), e+e- at the EE4 energies past the
        class's lower edge with catalog_v4_ee's cards (as ee4_)
  H7E   the classes at sqrt(s_hat) 6-20 TeV: pp at 20 TeV with dsqrt_shat 6000 in the run card (recipes/
        catalog_v4_pp_E20), so every event lies in the axis's window; e+e- at 6, 10 and 20 TeV (the window's ends and
        its log midpoint rounded to 10 TeV)
  H7c   the classes at pT > 30 GeV: catalog_v4_pp's and catalog_v4_ee's cards with ptj, ptb, pta, ptl 30 (recipes/
        catalog_v4_pp_c30, catalog_v4_ee_c30); e+e- at the EE4 energies past the class's lower edge at that cut
  H6    the classes at alpha_s(M_Z) 0.13: the base's events as H2p5's (catalog_v4's cards, MadEvent's own alpha_s,
        which for pp follows the PDF's), labelled at alpha_s(sqrt(s_hat)) run at one loop from 0.13
        (lhe.label_alphas_mz, as physics.alpha_s sets the catalog's own pools)
  H5    (one-loop labels on Born events): not written yet, it needs a pipeline piece

Each pool: 2000 test events (the EE4/PP4 test measure), labelled at alpha_s(sqrt(s_hat)) run at one loop from 0.118
(as pp13v4_/ee4_), built in the layout every rebuilt catalog_v4 MadEvent pool has (par:v4_short_runs): complete runs
of 1000 events from one gridpack per energy at max(need, GRID_MIN) events' precision, only complete runs assembled,
COMPLETE_SHARE of them expected to complete (recipes/gen_catalog_v4_default.py complete_layout).
    python3 recipes/gen_catalog_v4_heldout_default.py
      -> recipes/catalog_v4_heldout_default_processes.yaml, recipes/catalog_v4_heldout_default_test.yaml,
         recipes/catalog_v4_{pp,ee}_{E20,c30}/ (cards)
"""
import json
import os
import shutil
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)
from gen_catalog_v4_default import EE_ENERGIES, SMALL_RUN, complete_layout, lhe_entry  # noqa: E402

AXES = ("H2p5", "H6", "H7E", "H7c")
N_TEST = 2000
# pools whose runs of 1000 events outlast a run (step 18 probe logs, analysis/catalog_v4/data/lhe_rates_hd.json): smaller
# runs at the slow energies, as many as the share needs, in parallel (complete_layout sizes: {collider energy: (run
# size, complete share)}). Every run of these two that returned gave all 1000 events it asked (share 1.0); the slow
# energies' runs of 1000 took 340-1787 s and 1255 s or more (photon photon c cbar, 10 and 20 TeV) and 3509-3524 s and
# over 1790 s (c cbar d dbar, 10 and 20 TeV)
RUN_SIZES = {"v4_epem_aaccx__E20": {"10000": (250, 1.0), "20000": (250, 1.0)},
             "v4_epem_ccxddx__E20": {"10000": (250, 1.0), "20000": (250, 1.0)}}
E20_EE = (6000.0, 10000.0, 20000.0)
CARDS = {  # cards dir -> (source dir, run-card values patched)
    "recipes/catalog_v4_pp_E20": ("recipes/catalog_v4_pp", {"ebeam1": 10000.0, "ebeam2": 10000.0,
                                                            "dsqrt_shat": 6000.0}),
    "recipes/catalog_v4_pp_c30": ("recipes/catalog_v4_pp", {"ptj": 30.0, "ptb": 30.0, "pta": 30.0, "ptl": 30.0}),
    "recipes/catalog_v4_ee_c30": ("recipes/catalog_v4_ee", {"ptj": 30.0, "ptb": 30.0, "pta": 30.0, "ptl": 30.0}),
}
HDR = "# generated by recipes/gen_catalog_v4_heldout_default.py (held-out default-sampled test pools); do not edit\n"


def write_cards(mg):
    for dst, (src, patch) in CARDS.items():
        d, s = os.path.join(ROOT, dst), os.path.join(ROOT, src)
        os.makedirs(d, exist_ok=True)
        shutil.copy2(os.path.join(s, "param_card.dat"), os.path.join(d, "param_card.dat"))
        shutil.copy2(os.path.join(s, "run_card.dat"), os.path.join(d, "run_card.dat"))
        mg.patch_card(os.path.join(d, "run_card.dat"), patch)
        txt = open(os.path.join(d, "run_card.dat")).read()
        for k, v in patch.items():       # every value really set (a key the card lacks would pass silently)
            assert any(ln.split("=")[0].strip() == f"{v}" and ln.split("=")[1].split("!")[0].strip() == k
                       for ln in txt.splitlines() if "=" in ln and not ln.lstrip().startswith("#")), (dst, k)


def settings(ax, e, lo):
    """(cards dir, e+e- energies or None) of held-out entry e of axis ax (lo: its window's lower edge)."""
    ee = abs(int(e["pdg_ids"][0])) in (11, 13)
    if ax == "H7E":
        return ("recipes/catalog_v4_ee", list(E20_EE)) if ee else ("recipes/catalog_v4_pp_E20", None)
    cut = "_c30" if ax == "H7c" else ""
    if ee:
        return f"recipes/catalog_v4_ee{cut}", [E for E in EE_ENERGIES if E > lo]
    return f"recipes/catalog_v4_pp{cut}", None


def main():
    import mg5_pipeline_final as mg
    write_cards(mg)
    have = {n.split("_", 1)[1] for f in ("catalog_v4_pp_test.yaml", "catalog_v4_ee_test.yaml")
            for n in (p["name"] for p in yaml.safe_load(open(os.path.join(HERE, f)))["processes"])}
    hdr = {"run_card": "run_card.dat", "param_card": "param_card.dat", "model": mg.V4_MODEL,
           "n_val": 0, "n_test": N_TEST, "n_train": 0, "label_alphas": "running_sqrt_shat", "parts": True,
           "source": "catalog_v4's parameter card; catalog_v4_pp's or catalog_v4_ee's run card at the axis's energy "
                     "or cut (recipes/gen_catalog_v4_heldout_default.py)"}
    out, per_axis, skipped = {}, {}, []
    for ax in AXES:
        for h in yaml.safe_load(open(os.path.join(HERE, f"catalog_v4_heldout_{ax}.yaml")))["processes"]:
            n = h["name"]
            if not n.startswith("v4_") or n[3:] in have:
                continue
            base = h.get("base", n)
            e = mg.PROCESSES[base]
            cards, energies = settings(ax, e, float(h["sqrts"][0]))
            if energies == []:
                skipped.append(n); continue
            amz = (h.get("physics") or {}).get("alpha_s")
            lhe = {**hdr, "cards_dir": cards, **({"energies": energies} if energies else {}),
                   **({"label_alphas_mz": float(amz)} if amz is not None else {})}
            lhe = complete_layout(lhe, SMALL_RUN, gridpack=True, name=n, sizes=RUN_SIZES.get(n))
            lhe = {k: v for k, v in lhe.items() if k not in hdr or hdr[k] != v}
            name = "hd_" + n[3:]
            out[name] = {**lhe_entry(mg, base, e, mg.V4_MODEL, lhe), "parent": base, "split": "heldout",
                         "test_group": f"held-out default v4: {ax}", "heldout_class": n}
            per_axis[ax] = per_axis.get(ax, 0) + 1
    with open(os.path.join(HERE, "catalog_v4_heldout_default_processes.yaml"), "w") as f:
        f.write(HDR)
        yaml.safe_dump({"lhe": hdr, "processes": out}, f, sort_keys=False)
    with open(os.path.join(HERE, "catalog_v4_heldout_default_test.yaml"), "w") as f:
        f.write(HDR)
        yaml.safe_dump({"processes": [{"name": k, "sqrts": [13000, 13000], "n_train": 0, "n_val": 0,
                                       "n_test": N_TEST} for k in out]}, f, sort_keys=False)
    runs = sum(sum(e["lhe"]["energy_runs"]) if e["lhe"].get("energy_runs") else
               int(e["lhe"]["n_runs"]) * len(e["lhe"].get("energies") or [1]) for e in out.values())
    grids = sum(len(e["lhe"].get("energies") or [1]) for e in out.values())
    print(json.dumps({"pools": len(out), "per_axis": per_axis, "below_every_energy": skipped, "runs": runs,
                      "gridpacks": grids}))


if __name__ == "__main__":
    main()
