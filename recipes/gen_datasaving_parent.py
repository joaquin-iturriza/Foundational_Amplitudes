#!/usr/bin/env python3
"""pretrain_data_saving's parent recipes (D392, D400): catalog_v4's training recipe of trial 1262
(recipes/catalog_v4_default25_train.yaml) plus every tree class with an external top at the physical mass, holding out
only what leaks into the four draft Fig. 22 targets (e+e- > u u~ and t t~, LO and one-loop):
  the e+e- > t t~ family at every mass, tree and one loop (gen_kit_pretrain.family_of == "ee_tt": v4_epem_ttx, its
      __mt50/300/600 variants; v4_epem_ttx_nlo is in no training recipe)
  e+e- > u u~'s equality class (analysis/process_equality: ee_cc = ee_uu = uubar_mumu), its Z' variants, the tau-mass
      variant of u u~ > l l, and their one-loops (DROP)
The physical-mass tops come from catalog_v4's H3 recipe (recipes/catalog_v4_heldout_H3.yaml): catalog_v4 holds out
every class with an external top (axis H3, select_catalog_v4.py; the heavy-quark layer at m_Q = 50, 300, 600 brackets
it), so the training recipe has none (D400: "these two things scream to me as the problem"). They keep the H3 recipe's
sampling (catalog_v4's mixture, no default share: their val/test pools are built so). None has a train pool at that
sampling on CC (checked 2026-11-11; the cache's _smixq ones are another sampling), so they take n_train 1e4, all the
parent reads (data.train_subsample=10000, D393), built first by scripts/job_catalog_v4_regen.sh from
recipes/catalog_v4_datasaving_h3_train.yaml (the 278 entries alone, also written here).

    python recipes/gen_datasaving_parent.py   ->  recipes/catalog_v4_datasaving_parent_heldout.yaml
                                              and recipes/catalog_v4_datasaving_parent_treesin.yaml
The second is the one-loop targets' parent (the entry's words: "the one loops with the tree levels in the
pretraining"): the held-out recipe plus the two LO targets' own entries (recipes/catalog_v4_datasaving_{ee_uu,
epem_ttx}.yaml, each with its recipe's sampling), the one-loops still out.
"""
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_kit_pretrain import family_of  # noqa: E402

DROP = ["v4_epem_ccx", "v4_epem_ccx_nlo", "v4_zp_ee_uu", "v4_zp_uux_mumu", "v4_uux_taptam", "v4_uux_taptam_nlo"]

rec = yaml.safe_load(open(os.path.join(HERE, "catalog_v4_default25_train.yaml")))
h3 = yaml.safe_load(open(os.path.join(HERE, "catalog_v4_heldout_H3.yaml")))
names = [p["name"] for p in rec["processes"]]
missing = [n for n in DROP if n not in names]
assert not missing, f"not in the training recipe: {missing}"
assert not {p["name"] for p in h3["processes"]} & set(names), "an H3 class in the training recipe"
tops = [{**p, "sampling": h3["sampling"], "n_train": 10000} for p in h3["processes"] if family_of(p["name"]) != "ee_tt"]
with open(os.path.join(HERE, "catalog_v4_datasaving_h3_train.yaml"), "w") as f:
    f.write("# generated by recipes/gen_datasaving_parent.py; do not edit: the parents' physical-mass top classes, "
            "to prebuild their 1e4-event train pools\n")
    yaml.safe_dump({"sampling": h3["sampling"], "processes": tops}, f, sort_keys=False)
out_ = [p["name"] for p in rec["processes"] if p["name"] in DROP or family_of(p["name"]) == "ee_tt"]
rec["processes"] = [p for p in rec["processes"] if p["name"] not in out_] + tops
assert not [p for p in rec["processes"] if family_of(p["name"]) == "ee_tt" or p["name"] in DROP]
print(f"{len(names)} training pools - {len(out_)} held out ({', '.join(out_)}) + {len(tops)} physical-mass top "
      f"classes ({len(h3['processes']) - len(tops)} of H3 in the e+e- > t t~ family)")
out = os.path.join(HERE, "catalog_v4_datasaving_parent_heldout.yaml")
with open(out, "w") as f:
    f.write("# generated by recipes/gen_datasaving_parent.py; do not edit\n")
    yaml.safe_dump(rec, f, sort_keys=False)
print(f"{len(rec['processes'])} pools, wrote {out}")

for t in ("ee_uu", "epem_ttx"):
    tr = yaml.safe_load(open(os.path.join(HERE, f"catalog_v4_datasaving_{t}.yaml")))
    rec["processes"] += [{**p, "sampling": p.get("sampling", tr["sampling"])} for p in tr["processes"]]
out = os.path.join(HERE, "catalog_v4_datasaving_parent_treesin.yaml")
with open(out, "w") as f:
    f.write("# generated by recipes/gen_datasaving_parent.py; do not edit\n")
    yaml.safe_dump(rec, f, sort_keys=False)
print(f"{len(rec['processes'])} pools (the LO targets in), wrote {out}")
